export function resolveLocale(value: string | null | undefined): Locale {
  const locale = value?.trim().toLowerCase().split(/[-_]/)[0]
  return SUPPORTED_LOCALES.includes(locale as Locale) ? locale as Locale : DEFAULT_LOCALE
}

export function translate(locale: Locale, key: MessageKey, values: MessageValues = {}): string {
  const template = messages[locale][key] ?? messages[DEFAULT_LOCALE][key]
  return template.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match))
}

export function translateInterface(locale: Locale, source: string): string {
  if (locale === "es") return source
  const maxSideMatch = source.match(/^Cada lado debe tener como máximo ([\d,.]+) px\.$/)
  if (maxSideMatch) {
    return locale === "pt"
      ? `Cada lado deve ter no máximo ${maxSideMatch[1]} px.`
      : `Each side must be at most ${maxSideMatch[1]} px.`
  }
  return interfaceTranslations[source]?.[locale] ?? source
}

