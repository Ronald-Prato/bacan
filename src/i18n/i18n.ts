export function formatRelativeProjectUpdate(locale: Locale, updatedAt: number, now = Date.now()): string {
  const elapsed = Math.max(0, now - updatedAt)
  const elapsedMinutes = Math.floor(elapsed / 60_000)
  const elapsedHours = Math.floor(elapsed / 3_600_000)
  const elapsedDays = Math.floor(elapsed / 86_400_000)

  if (elapsedMinutes < 1) {
    return { en: "Edited just now", es: "Editado ahora", pt: "Editado agora" }[locale]
  }

  if (elapsedHours < 1) {
    return new Intl.RelativeTimeFormat(locale, { numeric: "always" }).format(-elapsedMinutes, "minute")
      .replace(/^/, { en: "Edited ", es: "Editado ", pt: "Editado " }[locale])
  }

  if (elapsedDays < 1) {
    return new Intl.RelativeTimeFormat(locale, { numeric: "always" }).format(-elapsedHours, "hour")
      .replace(/^/, { en: "Edited ", es: "Editado ", pt: "Editado " }[locale])
  }

  if (elapsedDays < 7) {
    return new Intl.RelativeTimeFormat(locale, { numeric: "always" }).format(-elapsedDays, "day")
      .replace(/^/, { en: "Edited ", es: "Editado ", pt: "Editado " }[locale])
  }

  const formattedDate = new Intl.DateTimeFormat(locale, { day: "numeric", month: "short" })
    .format(updatedAt)
    .replace(".", "")
  return {
    en: `Edited on ${formattedDate}`,
    es: `Editado el ${formattedDate}`,
    pt: `Editado em ${formattedDate}`,
  }[locale]
}
